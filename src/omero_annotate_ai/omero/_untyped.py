"""omero-py and ezomero, typed as ``Any``.

omero-py's classes and constants are generated by Ice at import time, and ezomero wraps
its functions in decorators that erase their signatures, so a static checker cannot see
their attributes. Importing them through this module keeps that blind spot in one place
instead of scattering ignores through the code that uses them.
"""

from importlib import import_module
from typing import Any

ezomero: Any = import_module("ezomero")
import_module("ezomero.rois")  # load the submodule so ``ezomero.rois`` resolves
omero_grid: Any = import_module("omero.grid")
omero_model: Any = import_module("omero.model")
omero_rtypes: Any = import_module("omero.rtypes")
NSBULKANNOTATIONS: str = import_module("omero.constants.namespaces").NSBULKANNOTATIONS

__all__ = ["NSBULKANNOTATIONS", "ezomero", "omero_grid", "omero_model", "omero_rtypes"]
